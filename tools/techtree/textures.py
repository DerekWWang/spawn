def colours_for(name, override=None):
    if override:
        return override
    low = name.lower()
    for keys, base, accent in MATERIAL_COLOURS:
        for k in keys:
            if k in low:
                return base, accent
    h = int(hashlib.md5(name.encode()).hexdigest(), 16)
    return DEFAULT_COLOURS[h % len(DEFAULT_COLOURS)]


def _shade(rgb, factor):
    r, g, b = rgb
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    l = max(0.0, min(1.0, l * factor if factor < 1 else l + (1 - l) * (factor - 1)))
    r2, g2, b2 = colorsys.hls_to_rgb(h, l, s)
    return int(r2 * 255), int(g2 * 255), int(b2 * 255)


def render_item(shape, name, path, override=None):
    base, accent = colours_for(name, override)
    tpl = [row for row in T[shape].strip("\n").split("\n")]
    assert len(tpl) == 16 and all(len(r) == 16 for r in tpl), (shape, [len(r) for r in tpl])
    palette = {
        "o": _shade(base, 0.35),
        "s": _shade(base, 0.72),
        "b": base,
        "h": _shade(base, 1.35),
        "x": accent,
        "w": (250, 250, 250),
    }
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(tpl):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            r, g, b = palette[ch]
            px[x, y] = (r, g, b, 255)
    img.save(path)


